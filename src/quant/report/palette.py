"""视觉常量的**单一事实来源**：色板 + 与图表共用的等宽字体栈。

为什么在 `src/quant/report/` 而不是 `app/`：面板（app/theme.py）和图表
（quant.report.charts）要用同一套配色，但 charts.py 属于库代码，不能反向 import
app/。于是把色板下沉到这里，两边各自 import——改一处、两边同步。

**这里是唯一定义处**：app/theme.py 与 quant.report.fmt 都只做转发别名
（`fmt.UP is palette.UP`），tests/test_charts.py 与 tests/test_theme.py
分别钉住"模块里不许再出现裸十六进制"。曾经的教训是面板改了暗色、图表还是
plotly 默认浅色模板，两边各写一套色值就会这样静默漂移。

依赖必须为零：charts.py 经由本模块取色，不能因此被拖进 streamlit 的 import。
"""
from __future__ import annotations

# ---------------------------------------------------------------- 基础四色
# 必须与 .streamlit/config.toml 一致（config.toml 里写不了 Python import，
# 由 tests/test_theme.py 比对钉住）。调性："金融电报"（旧交易所报价板）。
PRIMARY = "#C8963E"      # 琥珀金：可操作元素、选中态、强调
BACKGROUND = "#12141A"   # 近黑石板，非纯黑（纯黑对比过硬伤眼）
SURFACE = "#1A1D26"      # 卡片/侧栏，与底色只差一档
TEXT = "#E8E4DC"         # 暖白，非纯白

# ---------------------------------------------------------------- 方向色
# A 股惯例红涨绿跌。**全局铁律**：收益率、涨跌幅、盈亏、K 线一律用这两个色，
# 不许某处反过来（欧美习惯绿涨红跌，抄来的代码片段最容易在这里埋反向信号）。
UP = "#D94A4A"
DOWN = "#3E9E7A"
NEUTRAL = "#8C8778"      # 平盘/无方向：暖灰，不上色（§2.3 第 4 条"色只用在有意义处"）

# ---------------------------------------------------------------- 结构与状态
HAIRLINE = "#2A2E38"     # 发丝线：§2.3 第 2 条——1px 低对比分隔线，不用四面描边。
                         # 图表的网格线/零线也用它：暗底上白网格比数据还抢眼。
# pill 的底色：不用透明度（8 位十六进制读起来像魔法数），直接给四个压暗到能当底的值
UP_DIM = "#3A1F20"
DOWN_DIM = "#16302A"
PRIMARY_DIM = "#3A2E19"
MUTED_DIM = "#23262E"

# ---------------------------------------------------------------- 图表配色
# 折线的自动配色序列。**刻意不含 UP/DOWN**：红绿在本项目里专门表示涨跌，
# 一条红色的基准线就是个假信号（plotly 默认 colorway 的第 2、3 位恰好是红和绿）。
# 顺序 = 主角在前：策略曲线拿琥珀金，基准线退到灰与暖白。
CHART_SERIES = (PRIMARY, NEUTRAL, TEXT)

# ---------------------------------------------------------------- 字体
# 只有等宽栈是面板与图表共用的（图表的文字几乎全是数字与轴标签，衬线/无衬线
# 不参与），所以只有它下沉到这里。IBM Plex Mono 是纯拉丁小字体，浏览器实测
# 网络加载确实生效；Menlo / SF Mono 是 macOS 自带的离线兜底，不许省。
MONO = '"IBM Plex Mono", Menlo, "SF Mono", monospace'
